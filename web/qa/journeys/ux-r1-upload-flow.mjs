import { signedIn, WEB, SHOTS } from '../lib/session.mjs'
const { page, close, problems } = await signedIn('admin')
await page.goto(`${WEB}/clients`); await page.waitForTimeout(800)
await page.getByRole('button', { name: /New client/ }).click()
await page.getByLabel('Client name').fill('QA UX Test Traders')
const fy = page.getByLabel('Financial year starts'); await fy.fill('01-04-2025')
await page.getByRole('button', { name: 'Add client' }).click()
await page.waitForTimeout(2500)
console.log('URL', page.url())
await page.screenshot({ path: SHOTS + '/r1-ux-newclient-landing.png' })
console.log((await page.locator('main').innerText()).slice(0,700))
await page.getByRole('button', { name: 'Upload bank statement' }).first().click()
await page.locator('input[type=file]').setInputFiles('E:/autoca/web/qa/samples/qa-ux-traders-2025-04.pdf')
await page.waitForTimeout(400)
await page.screenshot({ path: SHOTS + '/r1-ux-upload-chosen.png' })
console.log('CHOSEN', (await page.locator('[role=dialog]').innerText()).slice(0,500))
await page.getByRole('button', { name: 'Upload and read' }).click()
for (let i = 0; i < 12; i++) {
  await page.waitForTimeout(1000)
  const t = (await page.locator('[role=dialog]').innerText().catch(() => '(no dialog) ' + page.url())).replace(/\n+/g, ' | ').slice(0, 300)
  console.log(i + 1, 's', t, '| live:', await page.locator('[aria-live],[role=status],[role=alert]').allInnerTexts())
  if (i === 1 || i === 4) await page.screenshot({ path: SHOTS + `/r1-ux-upload-progress-${i}.png` })
}
await page.screenshot({ path: SHOTS + '/r1-ux-upload-after.png' })
console.log('PROBLEMS', problems)
await close()
